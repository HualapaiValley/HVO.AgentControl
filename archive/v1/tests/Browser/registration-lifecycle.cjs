const { chromium, expect } = require('@playwright/test');
const fs = require('node:fs');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const base = process.env.HVO_BASE_URL || 'http://127.0.0.1:5056';
(async () => {
  const browser = await chromium.launch({headless:true,args:['--no-sandbox']});
  try {
    const context = await browser.newContext(); const page = await context.newPage();
    await page.goto(base+'/login');
    await page.getByLabel('Owner password').fill(fs.readFileSync(path.resolve(__dirname,'../../.fixture/secrets/owner-password'),'utf8').trim());
    await page.getByRole('button',{name:'Sign in',exact:true}).click();
    await expect(page.locator('.shell')).toHaveAttribute('data-interactive','true');
    const csrf = (await (await context.request.get(base+'/api/v1/csrf')).json()).token;
    const get = async p => (await context.request.get(base+'/api/v1'+p)).json();
    const post = async (p,data) => {
      const r = await context.request.post(base+'/api/v1'+p,{data,headers:{'X-CSRF-TOKEN':csrf}});
      if(!r.ok()) throw new Error(p+': '+await r.text()); return r.json();
    };
    const original = (await get('/snapshot')).runtimes[0];
    if (!original || !original.name.startsWith('Browser fixture')) throw new Error('Run smoke.cjs on a disposable test app first.');
    const id = randomUUID().replaceAll('-','');
    const runtime = await post('/runtimes',{...original,id,name:'Deletion fixture '+id,revision:0,desiredConnected:false,transport:'Disconnected',stateDirectory:'/home/agent/delete-'+id});
    const creation = await post('/workers',{id:randomUUID(),runtimeId:id,name:'Pending setup '+id,project:'Lifecycle',directory:'/home/agent/workspaces/pending-'+id,providerId:'fixture',modelId:'deterministic'});
    await page.goto(base+'/workers');
    const card = page.getByRole('article',{name:'Worker setup'}).filter({hasText:'Pending setup '+id});
    await expect(card).toContainText('Queued');
    await page.reload(); await expect(card).toContainText('Queued');
    await page.goto(base+'/runtimes'); await page.goto(base+'/workers'); await expect(card).toContainText('Queued');
    await card.getByRole('button',{name:'Cancel queued setup',exact:true}).click();
    await expect(card).toContainText('Cancelled');
    await card.getByRole('button',{name:'Edit setup',exact:true}).click();
    await expect(page.getByRole('region',{name:'New worker'}).getByLabel('Worker name')).toHaveValue('Pending setup '+id);
    await card.getByRole('button',{name:'Dismiss setup',exact:true}).click();
    await expect(card).toHaveCount(0); await page.reload(); await expect(card).toHaveCount(0);
    expect((await get('/commands/'+creation.id)).dismissed).toBe(true);
    await page.goto(base+'/runtimes');
    const unused = page.locator('article.runtime-card').filter({hasText:runtime.name});
    await unused.getByRole('button',{name:'Delete runtime',exact:true}).click();
    await unused.getByRole('button',{name:'Confirm delete runtime',exact:true}).click();
    await expect(unused).toHaveCount(0);
    const used = page.locator('article.runtime-card').filter({hasText:original.name});
    await used.getByRole('button',{name:'Delete runtime',exact:true}).click();
    await used.getByRole('button',{name:'Confirm delete runtime',exact:true}).click();
    await expect(page.getByRole('alert')).toContainText('Runtime is in use');
    await used.getByRole('button',{name:'Connect / ensure',exact:true}).click();
    await expect(used).toContainText('Connected',{timeout:40000});
    const bad = await post('/workers',{id:randomUUID(),runtimeId:original.id,name:'Failed setup '+id,project:'Lifecycle',directory:'/tmp',providerId:'fixture',modelId:'deterministic'});
    await page.goto(base+'/workers');
    const failed = page.getByRole('article',{name:'Worker setup'}).filter({hasText:'Failed setup '+id});
    await expect(failed.getByRole('status')).toHaveText('Failed',{timeout:30000});
    await expect(failed).toContainText('outside allowed roots');
    await page.reload(); await expect(failed).toContainText('outside allowed roots');
    await failed.getByRole('button',{name:'Dismiss setup',exact:true}).click();
    await expect(failed).toHaveCount(0);
    const worker = (await get('/snapshot')).workers.find(w=>w.runtimeId===original.id);
    const workerCard = page.locator('.worker-inventory article').filter({has:page.getByRole('heading',{name:worker.name,exact:true})});
    await workerCard.getByText('Details & management',{exact:true}).click();
    await expect(workerCard.getByRole('button',{name:'Archive worker',exact:true})).toBeEnabled({timeout:30000});
    await workerCard.getByRole('button',{name:'Delete worker',exact:true}).click();
    await expect(workerCard).toContainText('Deletion does not abort work or stop remote processes, so detached work may continue while disconnected.');
    await workerCard.getByRole('button',{name:'Confirm delete worker',exact:true}).click();
    await expect(workerCard).toHaveCount(0);
    await page.reload(); await expect(workerCard).toHaveCount(0);
    console.log('PASS: queued setup survives refresh/navigation; cancelled setup edit/dismiss; failed setup details persist; unused runtime deletion; in-use rejection; worker deletion warning and idle deletion.');
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
