using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

namespace HVO.AgentControl.Organization;

/// <summary>
/// The validated, canonical content of one immutable container profile
/// revision: a constrained <c>devcontainer.json</c> subset plus an optional
/// Dockerfile fragment that may only extend the approved worker base image.
/// </summary>
/// <remarks>
/// <para>
/// The subset is deliberately closed. Every accepted key is listed in
/// <see cref="AllowedKeys"/>; every key that would change host placement,
/// mounts, ports, privileges, users or the entrypoint is rejected fail-closed
/// with a key-specific reason (<see cref="ForbiddenKeys"/>), and any other key
/// is rejected as unknown. Runtime arguments, volumes, the network mode, the
/// employee/bridge users and the supervisor entrypoint remain controller-owned
/// and are never derived from profile content.
/// </para>
/// <para>
/// Definitions reference the approved worker base symbolically as
/// <see cref="BaseImageReference"/>. The concrete digest is pinned when a
/// revision is built on a host and frozen again at hire approval; the
/// revision itself stays immutable and hermetically validatable without any
/// deployment configuration.
/// </para>
/// </remarks>
public sealed partial class ContainerProfileDefinition
{
    /// <summary>Symbolic reference to the approved worker base image.</summary>
    public const string BaseImageReference = "agentcontrol-worker-base";

    public const int MaximumDefinitionBytes = 64 * 1024;
    public const int MaximumDockerfileFragmentBytes = 16 * 1024;
    public const int MaximumDockerfileFragmentLines = 200;
    public const int MaximumNameLength = 128;
    public const int MaximumEnvironmentValueLength = 256;
    public const int MaximumCommandLength = 1024;
    public const int MaximumCommandArgumentLength = 256;
    public const int MaximumCommandArguments = 16;
    public const int MaximumSummaryLength = 512;
    public const int MaximumTags = 8;
    public const int MaximumTagLength = 32;
    public const int MaximumJsonDepth = 6;

    /// <summary>Root keys this build accepts. Everything else is rejected.</summary>
    public static readonly IReadOnlyList<string> AllowedKeys =
    [
        "name", "image", "build", "features", "containerEnv", "remoteEnv",
        "postCreateCommand", "postStartCommand", "customizations",
    ];

