// Called only with HVO_CONTROL_SERVICE_FIXTURE=1 against disposable seeded data.
module.exports = async ({ page, context, base, expect }) => {
  await page.goto(base + '/control-services');
  await expect(page.locator('.shell')).toHaveAttribute('data-interactive', 'true');
  const service = page.getByRole('region', { name: 'Control service Browser control sidecar', exact: true });
  const host = service.getByRole('article', { name: 'Control session host', exact: true });
  const pending = service.getByRole('article', { name: 'Control session browser-workgroup', exact: true });
  await expect(pending).toContainText('Needs reconciliation');
  await expect(pending).toContainText('Native session creation unconfirmed');
  await pending.getByText('Session receipt', { exact: true }).click();
  const receipt = pending.getByRole('link', { name: 'control-browser-create-browser-workgroup', exact: true });
  const savedReceipt = await (await context.request.get(base + await receipt.getAttribute('href'))).json();
  expect(savedReceipt.state).toBe('DeliveryUnknown');
  const rejected = service.getByRole('article', { name: 'Control session browser-rejected', exact: true });
  await rejected.getByRole('button', { name: 'Retry creation', exact: true }).click();
  await expect(rejected).toContainText('Queued');
  const retriedServices = await (await context.request.get(base + '/api/v1/control-services')).json();
  const retried = retriedServices[0].sessions.find(x => x.scopeId === 'browser-rejected');
  expect(retried.creationCommandId).not.toBe('control-browser-create-browser-rejected');
  const priorRejected = await (await context.request.get(base + '/api/v1/commands/control-browser-create-browser-rejected')).json();
  expect(priorRejected.state).toBe('Failed');
  await expect(pending.getByRole('button', { name: 'Retry creation', exact: true })).toHaveCount(0);
  await expect(service.getByRole('button', { name: 'Add workgroup session', exact: true })).toBeDisabled();
  await expect(service.getByRole('link', { name: 'Open admin terminal', exact: true })).toHaveCount(0);
  await host.getByRole('button', { name: 'Edit session model', exact: true }).click();
  const editor = host.getByRole('region', { name: 'Edit control session', exact: true });
  await editor.getByRole('combobox', { name: 'Model', exact: true }).selectOption('fixture/replacement');
  await editor.getByRole('combobox', { name: 'Reasoning', exact: true }).selectOption('high');
  await editor.getByRole('button', { name: 'Save session settings', exact: true }).click();
  await expect(editor).toHaveCount(0);
  await expect(host).toContainText('fixture/replacement · high');
  const updated = await (await context.request.get(base + '/api/v1/workers/control-browser-host')).json();
  expect(updated.worker.modelId).toBe('replacement');
  expect(updated.worker.nativeSessionId).toBe('ses_browser_persistent_control');
  const queued = updated.commands.find(x => x.id === 'control-browser-queued-prompt');
  expect(queued.state).toBe('Queued');
  expect(JSON.parse(queued.executionPayload).modelId).toBe('original');
  expect(JSON.parse(queued.executionPayload).variant).toBe('medium');
  await page.reload();
  await expect(page.locator('.shell')).toHaveAttribute('data-interactive', 'true');
  await expect(pending).toContainText('Needs reconciliation');
  await expect(host).toContainText('fixture/replacement · high');
  await service.getByText('Service identity and restart', { exact: true }).click();
  await expect(service).toContainText('browser-persistent-instance');
  await expect(service).toContainText('browser-process-instance');
  await page.getByRole('button', { name: 'Collapse worker sidebar', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.locator('.worker-sidebar').evaluate(el => el.getBoundingClientRect().right)).toBeLessThanOrEqual(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  await page.setViewportSize({ width: 1280, height: 900 });
  await page.getByRole('button', { name: 'Expand worker sidebar', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Collapse worker sidebar', exact: true })).toBeVisible();
  await expect.poll(() => page.evaluate(() => localStorage.getItem('hvo.agentcontrol.sidebar-collapsed'))).toBe('false');
  await page.goto(base + '/');
  await expect(page.locator('.shell')).toHaveAttribute('data-interactive', 'true');
  await expect(page.getByRole('link', { name: 'View control service status', exact: true })).toHaveAttribute('href', '/control-services');
  const fleet = await (await context.request.get(base + '/api/v1/snapshot')).json();
  const expectedRuntimes = fleet.runtimes.filter(x => x.connectionKind === 'Ssh').length;
  await expect(page.getByRole('region', { name: 'Fleet overview', exact: true }).locator('small').first()).toHaveText('/ ' + expectedRuntimes);
  await page.goto(base + '/coordination');
  await expect(page.locator('.shell')).toHaveAttribute('data-interactive', 'true');
  await expect(page.getByLabel('Coordinator', { exact: true }).locator('option[value="control-browser-host"]')).toHaveCount(0);
  await page.goto(base + '/runtimes');
  await expect(page.locator('.shell')).toHaveAttribute('data-interactive', 'true');
  await expect(page.getByRole('heading', { name: 'Browser control sidecar', exact: true })).toHaveCount(0);
  await page.goto(base + '/workers');
  await expect(page.locator('.shell')).toHaveAttribute('data-interactive', 'true');
  await expect(page.getByRole('option', { name: 'Browser control sidecar', exact: true })).toHaveCount(0);
  await expect(page.getByRole('navigation', { name: 'Conversations' }).getByRole('region', { name: 'Browser control sidecar', exact: true })).toHaveCount(0);
};
